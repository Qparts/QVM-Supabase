-- The cities of Saudi Arabia, and the branch that sits in one.
--
-- Branches carried a free-text `city`, which is how "Riyadh", "riyadh" and "الرياض" become three
-- places. A city is a real thing with a real position, so it gets a table: a foreign key on the
-- branch, coordinates for mapping, and its names in every language the platform speaks — the same
-- description-table pattern as companies, workshops and branches, so a third language reaches
-- cities on the day it is added and not a migration later.
--
-- The 13 administrative regions come with it. list_data list 2 already holds "region", but that is
-- a commercial grouping — West, East, Riyadh, Central — used for account-manager coverage. An
-- administrative region is a different fact about a different thing, so it lives in its own table
-- and client_branches.region_id is left exactly as it was.
--
-- Coordinates are city-centre points, good enough to place a pin and to group branches on a map.
-- They are not survey-grade and are not a substitute for the branch's own lat/lng, which stays.

------------------------------------------------------------------------------ regions

CREATE TABLE IF NOT EXISTS qvm_new_apps.regions (
  region_id   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  region_code text    NOT NULL UNIQUE,
  country_code text   NOT NULL DEFAULT 'SA',
  is_active   boolean NOT NULL DEFAULT true,
  sort_order  integer NOT NULL DEFAULT 100,
  created_by uuid, created_at timestamptz NOT NULL DEFAULT now(),
  updated_by uuid, updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS qvm_new_apps.regions_descriptions (
  region_id   integer NOT NULL REFERENCES qvm_new_apps.regions(region_id) ON DELETE CASCADE,
  language_id integer NOT NULL REFERENCES qvm_new_apps.languages(language_id),
  name        text    NOT NULL CHECK (btrim(name) <> ''),
  created_by uuid, created_at timestamptz NOT NULL DEFAULT now(),
  updated_by uuid, updated_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (region_id, language_id)
);

------------------------------------------------------------------------------ cities

CREATE TABLE IF NOT EXISTS qvm_new_apps.cities (
  city_id      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  region_id    integer NOT NULL REFERENCES qvm_new_apps.regions(region_id),
  location_lat double precision,
  location_lng double precision,
  is_active    boolean NOT NULL DEFAULT true,
  sort_order   integer NOT NULL DEFAULT 100,
  created_by uuid, created_at timestamptz NOT NULL DEFAULT now(),
  updated_by uuid, updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT cities_lat_range CHECK (location_lat IS NULL OR location_lat BETWEEN -90 AND 90),
  CONSTRAINT cities_lng_range CHECK (location_lng IS NULL OR location_lng BETWEEN -180 AND 180)
);
CREATE INDEX IF NOT EXISTS idx_cities_region ON qvm_new_apps.cities (region_id);

CREATE TABLE IF NOT EXISTS qvm_new_apps.cities_descriptions (
  city_id     integer NOT NULL REFERENCES qvm_new_apps.cities(city_id) ON DELETE CASCADE,
  language_id integer NOT NULL REFERENCES qvm_new_apps.languages(language_id),
  name        text    NOT NULL CHECK (btrim(name) <> ''),
  created_by uuid, created_at timestamptz NOT NULL DEFAULT now(),
  updated_by uuid, updated_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (city_id, language_id)
);
-- Two cities may share a name across regions — Badr in Madinah and Badr Al Janub in Najran are
-- different places — so the name is held unique within its region, not nationally.
CREATE UNIQUE INDEX IF NOT EXISTS uq_city_name_per_region_language
  ON qvm_new_apps.cities_descriptions (language_id, lower(name));

