ALTER TABLE qvm_new_apps.client_branches
  ADD COLUMN IF NOT EXISTS city_id integer REFERENCES qvm_new_apps.cities(city_id);
CREATE INDEX IF NOT EXISTS idx_client_branches_city ON qvm_new_apps.client_branches (city_id);

ALTER TABLE qvm_new_apps.client_workshops
  ADD COLUMN IF NOT EXISTS city_id integer REFERENCES qvm_new_apps.cities(city_id);

-- Match what is already typed, in either language, and leave the free-text column alone: it is the
-- record of what someone wrote, and the rows that fail to match are exactly the ones worth seeing.
UPDATE qvm_new_apps.client_branches b
SET city_id = m.city_id
FROM (SELECT d.city_id, lower(btrim(d.name)) AS name FROM qvm_new_apps.cities_descriptions d) m
WHERE b.city_id IS NULL AND lower(btrim(COALESCE(b.city, ''))) = m.name;

UPDATE qvm_new_apps.client_workshops w
SET city_id = m.city_id
FROM (SELECT d.city_id, lower(btrim(d.name)) AS name FROM qvm_new_apps.cities_descriptions d) m
WHERE w.city_id IS NULL AND lower(btrim(COALESCE(w.city, ''))) = m.name;

------------------------------------------------------------------------------ resolved views

CREATE OR REPLACE VIEW qvm_new_apps.v_regions AS
SELECT r.region_id, r.region_code, r.country_code, r.is_active, r.sort_order,
       d.name, d.language_id AS name_language_id
FROM qvm_new_apps.regions r
LEFT JOIN LATERAL (
  SELECT d.* FROM qvm_new_apps.regions_descriptions d
   WHERE d.region_id = r.region_id
   ORDER BY (d.language_id = qvm_new_apps.current_language_id()) DESC,
            (d.language_id = qvm_new_apps.default_language_id()) DESC, d.language_id
   LIMIT 1
) d ON true;

CREATE OR REPLACE VIEW qvm_new_apps.v_cities AS
SELECT c.city_id, c.region_id, c.location_lat, c.location_lng, c.is_active, c.sort_order,
       d.name, d.language_id AS name_language_id,
       vr.name AS region_name, vr.region_code
FROM qvm_new_apps.cities c
JOIN qvm_new_apps.v_regions vr ON vr.region_id = c.region_id
LEFT JOIN LATERAL (
  SELECT d.* FROM qvm_new_apps.cities_descriptions d
   WHERE d.city_id = c.city_id
   ORDER BY (d.language_id = qvm_new_apps.current_language_id()) DESC,
            (d.language_id = qvm_new_apps.default_language_id()) DESC, d.language_id
   LIMIT 1
) d ON true;

GRANT SELECT ON qvm_new_apps.v_cities, qvm_new_apps.v_regions TO authenticated;

------------------------------------------------------------------------------ readable by the app

-- Every signed-in user needs the city list: it fills the pickers on the branch and workshop forms.
CREATE OR REPLACE FUNCTION public.list_cities() RETURNS jsonb
LANGUAGE sql STABLE SECURITY DEFINER SET search_path TO '' AS $$
  SELECT jsonb_build_object('success', true, 'data', COALESCE((
    SELECT jsonb_agg(jsonb_build_object(
             'city_id', c.city_id, 'name', c.name,
             'region_id', c.region_id, 'region_name', c.region_name, 'region_code', c.region_code,
             'location_lat', c.location_lat, 'location_lng', c.location_lng)
           ORDER BY c.region_code, c.name)
      FROM qvm_new_apps.v_cities c WHERE c.is_active), '[]'::jsonb));
$$;

GRANT EXECUTE ON FUNCTION public.list_cities() TO authenticated;
