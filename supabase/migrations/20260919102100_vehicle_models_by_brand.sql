-- Vehicle models, by brand, for the RFQ form.
--
-- The vehicle brand on an RFQ has always been a list_data row (list car_brand); the model was free
-- text. This adds the models the team keeps for the Saudi market — 1297 of them across
-- 143 brands — so that choosing a brand offers its models, and typing something else
-- remains possible for the one that is not on the list.
--
-- Brands are matched to list_data BY NAME; the ids in the source sheet are ignored. 63 of
-- the sheet's brands had no list_data row and are added to the car_brand list here, so their models
-- have something to hang off. Where list_data already had the brand under a different spelling
-- (Mercedes-Benz / MERCEDES, Lincoln / LINCOLEN, Peugeot / PEOGEUT, Exeed / Exceed, Tank / TANK,
-- GREAT WALL, Mini / MINI COOPER) the existing row is used. list_data carries BYD twice; the lower id
-- is used, which is the deterministic choice until someone merges them.

CREATE TABLE IF NOT EXISTS qvm_new_apps.vehicle_models (
  model_id   bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  brand_id   bigint  NOT NULL REFERENCES qvm_new_apps.list_data (list_data_id),
  name_en    text    NOT NULL,
  name_ar    text,
  is_active  boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_vehicle_models_brand_name
  ON qvm_new_apps.vehicle_models (brand_id, lower(name_en));
GRANT ALL ON qvm_new_apps.vehicle_models TO service_role;
GRANT SELECT ON qvm_new_apps.vehicle_models TO authenticated;

