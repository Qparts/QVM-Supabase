CREATE OR REPLACE FUNCTION qvm_new_apps.list_vehicle_models(p_brand_id bigint)
 RETURNS jsonb
 LANGUAGE sql
 STABLE
 SECURITY DEFINER
 SET search_path TO 'qvm_new_apps', 'public'
AS $function$
  SELECT COALESCE(jsonb_agg(jsonb_build_object(
           'model_id', m.model_id, 'brand_id', m.brand_id, 'name_en', m.name_en, 'name_ar', m.name_ar)
           ORDER BY m.name_en), '[]'::jsonb)
    FROM qvm_new_apps.vehicle_models m
   WHERE m.brand_id = p_brand_id AND m.is_active;
$function$;
CREATE OR REPLACE FUNCTION public.list_vehicle_models(p_brand_id bigint)
 RETURNS jsonb LANGUAGE sql SECURITY DEFINER SET search_path TO 'qvm_new_apps', 'public'
AS $$ SELECT qvm_new_apps.list_vehicle_models(p_brand_id); $$;
REVOKE ALL ON FUNCTION public.list_vehicle_models(bigint) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.list_vehicle_models(bigint) TO anon, authenticated, service_role;
GRANT EXECUTE ON FUNCTION qvm_new_apps.list_vehicle_models(bigint) TO anon, authenticated, service_role;
