CREATE OR REPLACE FUNCTION qvm_new_apps.generate_rfq_order_number(p_client_id integer, p_region_id integer)
 RETURNS text
 LANGUAGE plpgsql
 SECURITY DEFINER
AS $function$
declare
  v_prefix text;
  v_next int;
begin
  -- Get prefix
  select ons.prefix
  into v_prefix
  from qvm_new_apps.order_number_sequences ons
  where ons.lists_data_id = p_client_id
    and ons.region_id = p_region_id;

  if not found then
    raise exception 'Order sequence not configured for client % and region %',
      p_client_id, p_region_id;
  end if;

  -- Lock matching rows
  perform 1
  from qvm_new_apps.quotations q
  where q.order_number like v_prefix || '%'
  for update;

  -- Calculate next number safely
  select coalesce(
    max(
      nullif(regexp_replace(q.order_number, '.*?(\d+)$', '\1'), '')::int
    ),
    0
  ) + 1
  into v_next
  from qvm_new_apps.quotations q
  where q.order_number like v_prefix || '%';

  return v_prefix || v_next;
end;
$function$
;

