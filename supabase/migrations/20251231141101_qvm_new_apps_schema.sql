CREATE OR REPLACE FUNCTION qvm_new_apps.get_part_costs_history(p_parts jsonb)
 RETURNS jsonb
 LANGUAGE plpgsql
AS $function$DECLARE
  result JSONB;
BEGIN
  -- ✅ Guard: require non-empty array
  IF p_parts IS NULL OR jsonb_typeof(p_parts) <> 'array' OR jsonb_array_length(p_parts) = 0 THEN
    RETURN jsonb_build_object('status', false, 'message', 'p_parts must be a non-empty JSON array of objects');
  END IF;

  WITH parts AS (
    SELECT 
      regexp_replace(btrim(x->>'part_number'), '[\s\-/]', '', 'g') AS norm_part,
      (x->>'brand_class')::int AS brand_class
    FROM jsonb_array_elements(p_parts) AS x
    WHERE x ? 'part_number' AND x ? 'brand_class'
  ),
  -- From quotation_vendor_items
  qvi_base AS (
    SELECT
      qvi.created_at AS log_date,
      CONCAT('QVI', qvi.cost_id) AS id,
      qi.quotation_item_id,
      regexp_replace(btrim(qi.part_number), '[\s\-/]', '', 'g') AS norm_part,
      qi.part_number,
      q.order_number,
      cb.branch_name,
      qvi.cost,
      qvi.discount_percent,
      qvi.vendor_id,
      COALESCE(qvi.available_brand_class, qi.brand_class) AS effective_brand_class,
      qvi.cost * (1 - COALESCE(
                    CASE 
                      WHEN qvi.discount_percent > 1 THEN qvi.discount_percent / 100.0
                      ELSE qvi.discount_percent
                    END, 0)::numeric
                  ) AS net_cost
    FROM qvm_new_apps.quotation_vendor_items qvi
    JOIN qvm_new_apps.quotation_items qi ON qvi.quotation_item_id = qi.quotation_item_id
    JOIN qvm_new_apps.quotations q ON q.quotation_id = qi.quotation_id
    JOIN qvm_new_apps.client_branches cb ON cb.customer_id = qi.customer_id
    JOIN parts p 
      ON p.norm_part = regexp_replace(btrim(qi.part_number), '[\s\-/]', '', 'g')
     AND (
          -- prefer qvi.available_brand_class if set
          (qvi.available_brand_class IS NOT NULL AND qvi.available_brand_class = p.brand_class)
          OR
          -- otherwise fall back to quotation_items.brand_class
          (qvi.available_brand_class IS NULL AND qi.brand_class = p.brand_class)
         )
  ),
  -- From stock_files
  sf_base AS (
    SELECT
      sf.file_date AS log_date,
      CONCAT('SF', sf.id) AS id,
      NULL::BIGINT AS quotation_item_id,
      regexp_replace(btrim(sf.part_number), '[\s\-/]', '', 'g') AS norm_part,
      sf.part_number,
      'Stock File'::TEXT AS order_number,
      'Stock File'::TEXT AS branch_name,
      sf.cost_before_discount AS cost,
      sf.discount_percent,
      sf.vendor_id,
      sf.brand_class AS effective_brand_class,
      sf.cost_before_discount * (1 - COALESCE(
                    CASE 
                      WHEN sf.discount_percent > 1 THEN sf.discount_percent / 100.0
                      ELSE sf.discount_percent
                    END, 0)::numeric
                  ) AS net_cost
    FROM qvm_new_apps.stock_files sf
    JOIN parts p 
      ON p.norm_part = regexp_replace(btrim(sf.part_number), '[\s\-/]', '', 'g')
     AND p.brand_class = sf.brand_class
  ),
  unioned AS (
    SELECT * FROM qvi_base
    UNION ALL
    SELECT * FROM sf_base
  ),
  with_min AS (
    SELECT u.*,
           MIN(u.net_cost) OVER (PARTITION BY u.norm_part, u.effective_brand_class) AS min_cost_for_part
    FROM unioned u
  )
  SELECT jsonb_build_object(
           'status', TRUE,
           'message', 'success',
           'data', COALESCE(
             jsonb_agg(
               jsonb_build_object(
                 'log_date',          b.log_date,
                 'quotation_item_id', b.quotation_item_id,
                 'id',                b.id,
                 'part_number',       b.part_number,
                 'order_number',      b.order_number,
                 'branch_name',       b.branch_name,
                 'vendor_id',         b.vendor_id,
                 'cost',              b.cost,
                 'discount_percent',  b.discount_percent,
                 'net_cost',          b.net_cost,
                 'is_lowest_cost',    (b.net_cost = b.min_cost_for_part)
               )
               ORDER BY b.log_date DESC
             ),
             '[]'::jsonb
           )
         )
    INTO result
  FROM with_min b;

  RETURN result;
END;$function$
;

CREATE OR REPLACE FUNCTION qvm_new_apps.get_parts_pricing_history(p_parts jsonb)
 RETURNS jsonb
 LANGUAGE plpgsql
AS $function$DECLARE
  result jsonb;
BEGIN
  -- ✅ Guard: require non-empty array
  IF p_parts IS NULL OR jsonb_typeof(p_parts) <> 'array' OR jsonb_array_length(p_parts) = 0 THEN
    RETURN jsonb_build_object('status', false, 'message', 'p_parts must be a non-empty JSON array of objects');
  END IF;

  WITH parts AS (
    SELECT 
      regexp_replace(btrim(x->>'part_number'), '[\s\-/]', '', 'g') AS norm_part,
      (x->>'exclude_item_id')::bigint AS exclude_item_id
    FROM jsonb_array_elements(p_parts) AS x
    WHERE x ? 'part_number' AND x ? 'exclude_item_id'
  ),
  base AS (
    SELECT
      qvi.created_at                         AS log_date,
      qi.quotation_item_id,
      qi.part_number,
      q.order_number,
      cb.branch_name,
      qvi.cost,
      v.vendor_name,
      qi.price_before_vat
        * (1 - COALESCE(
                  CASE 
                    WHEN qi.discount_percent > 1 THEN qi.discount_percent / 100.0
                    ELSE qi.discount_percent
                  END, 0)::numeric
          )                                    AS selling_price,
      p.exclude_item_id,

      MIN(
        qi.price_before_vat
          * (1 - COALESCE(
                    CASE 
                      WHEN qi.discount_percent > 1 THEN qi.discount_percent / 100.0
                      ELSE qi.discount_percent
                    END, 0)::numeric
            )
      ) FILTER (WHERE qi.quotation_item_id <> p.exclude_item_id) 
        OVER (PARTITION BY qi.part_number)     AS min_price_for_part
    FROM qvm_new_apps.quotation_items qi
    JOIN qvm_new_apps.quotations q  
         ON q.quotation_id = qi.quotation_id
    JOIN qvm_new_apps.client_branches cb 
         ON cb.customer_id = qi.customer_id
    LEFT JOIN qvm_new_apps.quotation_vendor_items qvi 
         ON qvi.cost_id = qi.cost_id
    LEFT JOIN qvm_new_apps.vendors v  
         ON v.vendor_id = qvi.vendor_id
    JOIN parts p
      ON p.norm_part = regexp_replace(btrim(qi.part_number), '[\s\-/]', '', 'g')
  )
  SELECT jsonb_build_object(
           'status',  TRUE,
           'message', 'success',
           'data', COALESCE(
                       jsonb_agg(
                         jsonb_build_object(
                           'log_date',                b.log_date,
                           'quotation_item_id',       b.quotation_item_id,
                           'part_number',             b.part_number,
                           'order_number',            b.order_number,
                           'branch_name',             b.branch_name,
                           'cost',                    b.cost,
                           'vendor_name',             b.vendor_name,
                           'selling_price',           b.selling_price,
                           'is_lowest_selling_price', (b.selling_price = b.min_price_for_part)
                         )
                       ORDER BY b.log_date DESC),
                       '[]'::jsonb
                     )
         )
    INTO result
  FROM base b;

  RETURN result;
END;$function$
;

