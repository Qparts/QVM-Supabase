CREATE OR REPLACE FUNCTION qvm_new_apps.update_purchase_order_status(p_purchase_order_id bigint)
 RETURNS jsonb
 LANGUAGE plpgsql
AS $function$DECLARE
  new_status int;
BEGIN
  -- Collect info about items and purchase order
  WITH items AS (
    SELECT vendor_item_status
    FROM qvm_new_apps.purchase_items pi
    WHERE pi.purchase_order_id = p_purchase_order_id
  ),
  agg AS (
    SELECT 
      COUNT(*) AS total_items,
      COUNT(DISTINCT vendor_item_status) AS distinct_statuses,
      MIN(vendor_item_status) AS min_status,
      BOOL_OR(vendor_item_status = 159) AS has_159,
      BOOL_OR(vendor_item_status = 162) AS has_162,
      BOOL_OR(vendor_item_status = 163) AS has_163,
      BOOL_OR(vendor_item_status = 164) AS has_164
    FROM items
  ),
  po AS (
    SELECT vendor_invoice_url, vendor_return_url
    FROM qvm_new_apps.purchase_orders
    WHERE purchase_order_id = p_purchase_order_id
  )
  SELECT CASE
           -- At least one 159, and none in [162–169]
           WHEN (agg.has_159 AND NOT agg.has_162 AND NOT agg.has_163 AND NOT agg.has_164) THEN 159

           -- If any 162 → status = 162
           WHEN agg.has_162 THEN 162

           -- If no 162, but some 163 → status = 163
           WHEN (NOT agg.has_162 AND agg.has_163) THEN 163

           -- If no 162,163,159 but some 164 → status = 164
           WHEN (NOT agg.has_162 AND NOT agg.has_163 AND NOT agg.has_159 AND agg.has_164) THEN 164

           -- If invoice uploaded → 165
           WHEN po.vendor_invoice_url IS NOT NULL THEN 165

           -- If all items = 166
           WHEN agg.distinct_statuses = 1 AND agg.min_status = 166 THEN 166

           -- If all items = 167
           WHEN agg.distinct_statuses = 1 AND agg.min_status = 167 THEN 167

           -- If return URL uploaded → 168
           WHEN po.vendor_return_url IS NOT NULL THEN 168

           ELSE NULL
         END
  INTO new_status
  FROM agg, po;

  -- Update the vendor status if computed
  IF new_status IS NOT NULL THEN
    UPDATE qvm_new_apps.purchase_orders po
    SET vendor_status = new_status
        WHERE po.purchase_order_id = p_purchase_order_id;
  END IF;

  RETURN jsonb_build_object(
    'status', true,
    'message', 'Vendor status updated',
    'purchase_order_id', p_purchase_order_id,
    'new_status', new_status
  );
END;$function$
;

