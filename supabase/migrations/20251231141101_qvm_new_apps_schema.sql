CREATE OR REPLACE FUNCTION qvm_new_apps.update_approved_qty(p_updates jsonb)
 RETURNS json
 LANGUAGE plpgsql
AS $function$
DECLARE
  elem jsonb;
  v_item_id bigint;
  v_qty numeric;
  v_price numeric;
  v_total numeric;
  updated_count int := 0;
BEGIN
  -- Validate input
  IF p_updates IS NULL OR jsonb_typeof(p_updates) <> 'array' THEN
    RETURN json_build_object('success', false, 'message', 'Input must be a JSON array');
  END IF;

  -- Loop through updates array
  FOR elem IN SELECT * FROM jsonb_array_elements(p_updates)
  LOOP
    v_item_id := (elem->>'quotation_item_id')::bigint;
    v_qty     := (elem->>'approved_quantity')::numeric;

    IF v_item_id IS NULL OR v_qty IS NULL THEN
      CONTINUE;
    END IF;

    -- 1) Update approved_qty in confirmed_items
    UPDATE qvm_new_apps.confirmed_items
    SET approved_qty = v_qty
    WHERE quotation_item_id = v_item_id;

    -- 2) Fetch price_before_vat from quotation_items
    SELECT price_before_vat
    INTO v_price
    FROM qvm_new_apps.quotation_items
    WHERE quotation_item_id = v_item_id;

    -- 3) Update total_price_before_vat in quotation_items
    IF v_price IS NOT NULL THEN
      v_total := v_qty * v_price;
      UPDATE qvm_new_apps.quotation_items
      SET total_price_before_vat = v_total
      WHERE quotation_item_id = v_item_id;
    END IF;

    updated_count := updated_count + 1;
  END LOOP;

  RETURN json_build_object(
    'success', true,
    'updated_count', updated_count
  );
END;
$function$
;

