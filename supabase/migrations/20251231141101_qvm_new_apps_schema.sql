CREATE OR REPLACE FUNCTION qvm_new_apps.update_vendor_status(p_quotation_vendor_id bigint)
 RETURNS jsonb
 LANGUAGE plpgsql
AS $function$DECLARE
  new_status int;
BEGIN
  -- Compute aggregate flags
  WITH items AS (
    SELECT vendor_item_status
    FROM qvm_new_apps.quotation_vendor_items qvi
    WHERE qvi.quotation_vendor_id = p_quotation_vendor_id
  )
  SELECT CASE
           WHEN EXISTS (SELECT 1 FROM items WHERE vendor_item_status = 157) THEN 157
           WHEN EXISTS (SELECT 1 FROM items WHERE vendor_item_status = 159) THEN 159
           WHEN NOT EXISTS (SELECT 1 FROM items WHERE vendor_item_status IN (157,159))
                AND EXISTS (SELECT 1 FROM items WHERE vendor_item_status = 158) THEN 158
           WHEN (SELECT COUNT(DISTINCT vendor_item_status) FROM items) = 1
                AND (SELECT MIN(vendor_item_status) FROM items) = 160 THEN 160
           WHEN (SELECT COUNT(DISTINCT vendor_item_status) FROM items) = 1
                AND (SELECT MIN(vendor_item_status) FROM items) = 161 THEN 161
           ELSE NULL
         END
  INTO new_status;

  -- Update the vendor status
  IF new_status IS NOT NULL THEN
    UPDATE qvm_new_apps.quotation_vendors qv
    SET vendor_status = new_status,
        updated_at = now()
    WHERE qv.quotation_vendor_id = p_quotation_vendor_id;
  END IF;

  RETURN jsonb_build_object(
    'status', true,
    'message', 'Vendor status updated',
    'quotation_vendor_id', p_quotation_vendor_id,
    'new_status', new_status
  );
END;$function$
