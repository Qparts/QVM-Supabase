CREATE OR REPLACE FUNCTION qvm_new_apps.bulk_update_item_details(p_updates jsonb)
 RETURNS jsonb
 LANGUAGE plpgsql
AS $function$DECLARE
  elem                   JSONB;
  v_cost_id              INTEGER;
  v_q_item_id            INTEGER;
  v_alt_part             TEXT;
  v_new_part_number      TEXT;
  v_new_part_description TEXT;
  v_new_part_category    INTEGER;
  v_new_discount_percent FLOAT;
  v_new_price_before_vat FLOAT;
  v_rows_vend            INTEGER;
  v_rows_item            INTEGER;
  results                JSONB := '[]'::jsonb;
BEGIN
  IF p_updates IS NULL OR jsonb_typeof(p_updates) <> 'array' THEN
    RETURN jsonb_build_object('status', false, 'message', 'p_updates must be a JSON array');
  END IF;

  FOR elem IN SELECT * FROM jsonb_array_elements(p_updates)
  LOOP
    v_rows_vend := 0;
    v_rows_item := 0;

    v_q_item_id            := NULLIF(elem->>'quotation_item_id','')::INTEGER;
    v_alt_part             := NULLIF(elem->>'alternative_part_number','');
    IF elem ? 'part_number' THEN
  v_new_part_number := elem->>'part_number';  -- can be null or ''
END IF;
    v_new_part_description := NULLIF(elem->>'part_description','');
    v_new_part_category    := NULLIF(elem->>'part_category','')::INTEGER;
    v_new_discount_percent := NULLIF(elem->>'discount_percent','')::FLOAT;
    v_new_price_before_vat := NULLIF(elem->>'price_before_vat','')::FLOAT;

    -- Update quotation item (only fields provided)
    IF v_q_item_id IS NOT NULL THEN
      UPDATE qvm_new_apps.quotation_items
      SET part_number      = COALESCE(v_new_part_number, part_number),
          part_description = COALESCE(v_new_part_description, part_description),
          part_category    = COALESCE(v_new_part_category, part_category),
          alternative_part_number = COALESCE(v_alt_part, alternative_part_number),
          discount_percent  =COALESCE(v_new_discount_percent, discount_percent),
          price_before_vat  =COALESCE(v_new_price_before_vat, price_before_vat),          
          updated_at       = NOW()
      WHERE quotation_item_id = v_q_item_id;
      GET DIAGNOSTICS v_rows_item = ROW_COUNT;
    END IF;

    results := results || jsonb_build_array(
      jsonb_build_object(
        'cost_id', v_cost_id,
        'quotation_item_id', v_q_item_id,
        'updated_vendor_rows', v_rows_vend,
        'updated_item_rows', v_rows_item,
        'status', (COALESCE(v_rows_vend,0) + COALESCE(v_rows_item,0)) > 0
      )
    );
  END LOOP;

  RETURN jsonb_build_object(
    'status', true,
    'message', 'Bulk update processed',
    'count', jsonb_array_length(p_updates),
    'data', results
  );
END;$function$
;

