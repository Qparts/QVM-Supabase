CREATE OR REPLACE FUNCTION qvm_new_apps.get_items_pricing(p_quotation_item_ids bigint[])
 RETURNS jsonb
 LANGUAGE plpgsql
AS $function$DECLARE
  result jsonb;
BEGIN
  IF p_quotation_item_ids IS NULL OR array_length(p_quotation_item_ids, 1) IS NULL THEN
    RETURN jsonb_build_object('status', false, 'message', 'p_quotation_item_ids must be a non-empty bigint[]');
  END IF;

  WITH ids AS (
    SELECT DISTINCT unnest(p_quotation_item_ids) AS quotation_item_id
  ),
  totals AS (
    SELECT 
      qi.quotation_id,
      SUM(((qvi.cost::numeric * (1 + COALESCE(pm.percentage,0)::numeric)) * qi.quantity)::numeric) AS total_extended
    FROM qvm_new_apps.quotation_items qi
    JOIN ids ON ids.quotation_item_id = qi.quotation_item_id
    LEFT JOIN qvm_new_apps.quotation_vendor_items qvi ON qvi.cost_id = qi.cost_id
    LEFT JOIN qvm_new_apps.profit_categories pc
           ON pc.brand_class   = qi.brand_class
          AND pc.part_category = qi.part_category
    LEFT JOIN qvm_new_apps.cost_categories cc
           ON qvi.cost IS NOT NULL
          AND qvi.cost >= (cc.cost_range->>0)::numeric
          AND qvi.cost <  (cc.cost_range->>1)::numeric
    LEFT JOIN qvm_new_apps.profit_margins pm
           ON pm.profit_categories_id = pc.category_id
          AND pm.cost_range_id        = cc.cost_range_id
    GROUP BY qi.quotation_id
  )
  SELECT jsonb_build_object(
           'status', true,
           'message', 'success',
           'data', COALESCE(
             jsonb_agg(
               jsonb_build_object(
                 'quotation_item_id',  qi.quotation_item_id,
                 'quotation_id',       qi.quotation_id,
                 'price_before_vat',   qi.price_before_vat,
                 'cost_id',            qi.cost_id,
                 'purchase_cost',      qvi_pur.cost,
                 'purchase_vendor',    v_pur.vendor_name,
                 'profit_percentage',  COALESCE(pm.percentage, 0),
                 'profit_value',
                   CASE
                     WHEN qvi_pur.cost IS NOT NULL AND pm.percentage IS NOT NULL
                       THEN ROUND((qvi_pur.cost::numeric * pm.percentage::numeric)::numeric, 2)
                     ELSE NULL
                   END,
                 'selling_price',
                   CASE
                     WHEN (LOWER(q.shipping_type) = 'quotation' AND qvi_pur.cost IS NOT NULL AND pm.percentage IS NOT NULL) THEN
                       ROUND((qvi_pur.cost::numeric * (1 + pm.percentage::numeric))::numeric, 2)

                     WHEN (LOWER(q.shipping_type) = 'item' AND qvi_pur.cost IS NOT NULL AND pm.percentage IS NOT NULL) THEN
                       ROUND(
                         (
                           ((qvi_pur.cost::numeric * (1 + pm.percentage::numeric)) * qi.quantity)::numeric
                           + (
                               ((qvi_pur.cost::numeric * (1 + pm.percentage::numeric)) * qi.quantity)::numeric
                               / NULLIF(t.total_extended, 0)
                             ) * COALESCE(q.shipping_price::numeric, 0)
                         ) / NULLIF(qi.quantity,0),
                         2
                       )
                     ELSE NULL
                   END
               )
               ORDER BY qi.quotation_item_id DESC
             ),
             '[]'::jsonb
           )
         )
    INTO result
  FROM qvm_new_apps.quotation_items qi
  JOIN ids ON ids.quotation_item_id = qi.quotation_item_id
  LEFT JOIN qvm_new_apps.quotations q ON q.quotation_id = qi.quotation_id
  LEFT JOIN qvm_new_apps.quotation_vendor_items qvi_pur ON qvi_pur.cost_id = qi.cost_id
  LEFT JOIN qvm_new_apps.vendors v_pur ON v_pur.vendor_id = qvi_pur.vendor_id
  LEFT JOIN qvm_new_apps.profit_categories pc
         ON pc.brand_class   = qi.brand_class
        AND pc.part_category = qi.part_category
  LEFT JOIN qvm_new_apps.cost_categories cc
         ON qvi_pur.cost IS NOT NULL
        AND qvi_pur.cost >= (cc.cost_range->>0)::numeric
        AND qvi_pur.cost <  (cc.cost_range->>1)::numeric
  LEFT JOIN qvm_new_apps.profit_margins pm
         ON pm.profit_categories_id = pc.category_id
        AND pm.cost_range_id        = cc.cost_range_id
  LEFT JOIN totals t ON t.quotation_id = qi.quotation_id;

  RETURN result;
END;$function$
;

