CREATE OR REPLACE FUNCTION qvm_new_apps.refresh_rfq_search_index_incremental()
 RETURNS void
 LANGUAGE plpgsql
AS $function$
BEGIN
  DELETE FROM qvm_new_apps.rfq_search_index idx
WHERE
  -- Delete only if the quotation_item itself is gone
  NOT EXISTS (
    SELECT 1 FROM qvm_new_apps.quotation_items qi
    WHERE qi.quotation_item_id = idx.quotation_item_id
  )
  -- OR delete if a confirmed item ID is set AND the quotation no longer exists
  OR (
    idx.confirmed_item_id IS NOT NULL
    AND NOT EXISTS (
      SELECT 1 FROM qvm_new_apps.confirmed_items ci
      WHERE ci.confirmed_item_id = idx.confirmed_item_id
    )
    AND NOT EXISTS (
      SELECT 1 FROM qvm_new_apps.quotation_items qi
      WHERE qi.quotation_item_id = idx.quotation_item_id
    )
  );
  -- 3. Insert or update recent changes
  INSERT INTO qvm_new_apps.rfq_search_index (
    quotation_item_id,
    confirmed_item_id,
    search_vector
   )
  SELECT 
    qi.quotation_item_id,
    ci.confirmed_item_id,
    setweight(to_tsvector('simple', coalesce(qi.part_number, '')), 'A') ||
    setweight(to_tsvector('simple', coalesce(qi.part_description, '')), 'B') ||
    setweight(to_tsvector('simple', coalesce(lmb.list_data, '')), 'B') ||
    setweight(to_tsvector('simple', coalesce(ci.final_part_number, '')), 'B') ||
    setweight(to_tsvector('simple', coalesce(qi.vin, '')), 'C') ||
    setweight(to_tsvector('simple', coalesce(q.order_number, '')), 'D') ||
    setweight(to_tsvector('simple', coalesce(q.plate_number, '')), 'D')
  FROM qvm_new_apps.quotation_items qi
  JOIN qvm_new_apps.quotations q ON qi.quotation_id = q.quotation_id
  LEFT JOIN qvm_new_apps.list_data lmb ON qi.main_brand = lmb.list_data_id
  LEFT JOIN qvm_new_apps.confirmed_items ci ON qi.quotation_item_id = ci.quotation_item_id
  WHERE qi.updated_at >= NOW() - INTERVAL '1 minute'
     OR ci.updated_at >= NOW() - INTERVAL '1 minute'
  ON CONFLICT (quotation_item_id)
  DO UPDATE SET 
    confirmed_item_id = EXCLUDED.confirmed_item_id,
    search_vector     = EXCLUDED.search_vector;
END;
$function$
