    SELECT DISTINCT
      (x->>'stock_file_id')::bigint        AS stock_file_id, 
      (x->>'cost_before_discount')::float  AS cost_before_discount, 
      (x->>'discount_percent')::float      AS discount_percent
    FROM jsonb_array_elements(p_agency_price_update) AS x
    WHERE (x ? 'stock_file_id') AND (x ? 'cost_before_discount')
  ),
  u AS (
    UPDATE qvm_new_apps.stock_files sf
    SET
      cost_before_discount = upd.cost_before_discount,
      discount_percent     = upd.discount_percent,
      updated_at           = now()
    FROM upd
    WHERE sf.id = upd.stock_file_id
      -- prevent no-op writes
      AND (
        sf.cost_before_discount IS DISTINCT FROM upd.cost_before_discount
        OR sf.discount_percent  IS DISTINCT FROM upd.discount_percent
      )
    RETURNING
      sf.id,
      sf.cost_before_discount,
      sf.discount_percent
  )
  SELECT COALESCE(jsonb_agg(to_jsonb(u.*)), '[]'::jsonb)
  INTO updated_rows
  FROM u;

  RETURN jsonb_build_object(
    'status',  true,
    'message', 'Cost updated',
    'count',   COALESCE(jsonb_array_length(updated_rows), 0),
    'data',    updated_rows
  );
END;
