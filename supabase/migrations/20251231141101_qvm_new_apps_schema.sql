CREATE OR REPLACE FUNCTION qvm_new_apps.set_best_cost_for_items(p_item_ids bigint[])
 RETURNS void
 LANGUAGE plpgsql
AS $function$BEGIN
  IF p_item_ids IS NULL OR array_length(p_item_ids, 1) IS NULL THEN
    RETURN;
  END IF;

  -- Optional: lock the parent items so concurrent recomputes don't interleave
  PERFORM 1
  FROM qvm_new_apps.quotation_items qi
  WHERE qi.quotation_item_id = ANY (p_item_ids)
  FOR UPDATE;

  -- 1) Clear any current winners for these items
  WITH ids AS (
    SELECT DISTINCT unnest(p_item_ids) AS quotation_item_id
  )
  UPDATE qvm_new_apps.quotation_vendor_items q
  SET best_cost = FALSE
  FROM ids
  WHERE q.quotation_item_id = ids.quotation_item_id
    AND q.best_cost IS TRUE;

  -- 2) Compute winners and set them TRUE (only one per item)
  WITH ids AS (
    SELECT DISTINCT unnest(p_item_ids) AS quotation_item_id
  ),
  winners AS (
    SELECT DISTINCT ON (qvi.quotation_item_id)
           qvi.cost_id, qvi.quotation_item_id
    FROM qvm_new_apps.quotation_vendor_items qvi
    JOIN ids USING (quotation_item_id)
    JOIN qvm_new_apps.quotation_items qi
      ON qi.quotation_item_id = qvi.quotation_item_id
    WHERE qvi.cost IS NOT NULL
    AND (qvi.available_quantity >= qi.quantity
        OR qvi.available_quantity IS NULL)  -- optional rule
    AND (
        qvi.available_brand_class = qi.brand_class
        OR qvi.available_brand_class IS NULL
      )
    ORDER BY qvi.quotation_item_id, qvi.cost ASC, qvi.created_at ASC, qvi.cost_id ASC
  )
  UPDATE qvm_new_apps.quotation_vendor_items q
  SET best_cost = TRUE
  FROM winners w
  WHERE q.cost_id = w.cost_id
    AND q.best_cost IS DISTINCT FROM TRUE;

  -- 3) Mirror the winner cost_id onto quotation_items (redeclare CTEs!)
  WITH ids AS (
    SELECT DISTINCT unnest(p_item_ids) AS quotation_item_id
  ),
  winners AS (
    SELECT DISTINCT ON (qvi.quotation_item_id)
           qvi.cost_id, qvi.quotation_item_id
    FROM qvm_new_apps.quotation_vendor_items qvi
    JOIN ids USING (quotation_item_id)
    JOIN qvm_new_apps.quotation_items qi
      ON qi.quotation_item_id = qvi.quotation_item_id
    WHERE qvi.cost IS NOT NULL
    AND (qvi.available_quantity >= qi.quantity
        OR qvi.available_quantity IS NULL)  -- optional rule
    AND (
        qvi.available_brand_class = qi.brand_class
        OR qvi.available_brand_class IS NULL
      )
    ORDER BY qvi.quotation_item_id, qvi.cost ASC, qvi.created_at ASC, qvi.cost_id ASC
  )
  UPDATE qvm_new_apps.quotation_items qi
  SET cost_id    = w.cost_id,
      updated_at = NOW()
  FROM winners w
  WHERE qi.quotation_item_id = w.quotation_item_id
    AND qi.cost_id IS DISTINCT FROM w.cost_id;

END;$function$
;

