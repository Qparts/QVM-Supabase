CREATE OR REPLACE FUNCTION qvm_new_apps.get_stock_agency_prices(p_part_numbers text[])
 RETURNS jsonb
 LANGUAGE plpgsql
AS $function$DECLARE
  result jsonb;
BEGIN
  IF p_part_numbers IS NULL OR array_length(p_part_numbers,1) IS NULL THEN
    RETURN jsonb_build_object('status', false, 'message', 'p_part_numbers must be a non-empty text[]');
  END IF;

  WITH parts AS (
    -- normalize + dedupe inputs
    SELECT DISTINCT lower(regexp_replace(btrim(pn), '[\s\-/]', '', 'g')) AS norm_part
    FROM unnest(p_part_numbers) AS t(pn)
    WHERE pn IS NOT NULL AND btrim(pn) <> ''
  ),
  base AS (
    SELECT
      sf.id AS id,
      sf.file_date,
      sf.part_number,
      sf.part_description,
      sf.cost_before_discount,
      sf.discount_percent,
      v.vendor_name,
      v.vendor_type,
      ld.list_data AS brand_class,
      sf.made_in,

      -- normalized key for window partition
      lower(regexp_replace(btrim(sf.part_number), '[\s\-/]', '', 'g')) AS norm_part,

      -- discounted cost (treat NULL discount as 0)
      (sf.cost_before_discount * (1 - COALESCE(sf.discount_percent, 0))) AS cost_after_discount
    FROM qvm_new_apps.stock_files sf
    JOIN parts p
      ON p.norm_part = lower(regexp_replace(btrim(sf.part_number), '[\s\-/]', '', 'g'))
    JOIN qvm_new_apps.vendors v
      ON v.vendor_id = sf.vendor_id
     AND lower(trim(v.vendor_type)) = lower('وكيل')       -- remove this line to include all vendors
    LEFT JOIN qvm_new_apps.list_data ld
      ON ld.list_data_id = sf.brand_class
  ),
  with_max AS (
    SELECT
      b.*,
      -- max discounted cost across ALL vendors for the same normalized part
      MAX(b.cost_after_discount) OVER (PARTITION BY b.norm_part) AS max_agency_cost
    FROM base b
  )
  SELECT jsonb_build_object(
           'status',  TRUE,
           'message', 'success',
           'data', COALESCE(
             jsonb_agg(
               jsonb_build_object(
                 'id',        w.id,
                 'file_date',            w.file_date,
                 'part_number',          w.part_number,
                 'part_description',     w.part_description,
                 'cost_before_discount', w.cost_before_discount,
                 'discount_percent',     w.discount_percent,
                 'vendor_name',          w.vendor_name,
                 'vendor_type',          w.vendor_type,
                 'brand_class',          w.brand_class,
                 'made_in',              w.made_in,
                 'cost_after_discount',  w.cost_after_discount,
                 'max_agency_cost',      w.max_agency_cost,
                 'is_max_agency_cost',   (w.cost_after_discount = w.max_agency_cost) -- true for the winner(s)
               )
               ORDER BY w.part_number, w.file_date, w.vendor_name
             ),
             '[]'::jsonb
           )
         )
    INTO result
  FROM with_max w;

  RETURN result;
END;$function$
