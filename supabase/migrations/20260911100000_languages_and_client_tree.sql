-- Companies, workshops and branches — with every name translatable.
--
-- Three things arrive together because they only make sense together:
--
--   1. `languages` — the set of languages the platform speaks, managed from the admin UI. Adding
--      one is a row, never a migration.
--   2. `client_companies` and `client_workshops` — the two tiers above the branch. Companies stop
--      being list_data rows and become a table of their own, KEEPING THEIR EXISTING IDS so that
--      every user_data.user_company and client_branches.list_data_id already written stays valid.
--   3. `*_descriptions` tables — one row per record per language, carrying the name. A foreign key
--      on language_id makes a mistyped language code unrepresentable, which is the whole reason
--      this is a table and not a jsonb column.
--
-- The branch is untouched as an entity: client_branches.customer_id is foreign-keyed from nine
-- tables and named in 62 functions, and every quotation line ever raised points at it. It gains a
-- parent and a translation table; it does not move.

------------------------------------------------------------------------------ languages

CREATE TABLE IF NOT EXISTS qvm_new_apps.languages (
  language_id  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code         text    NOT NULL UNIQUE,          -- BCP-47: 'en', 'ar', 'ur'
  english_name text    NOT NULL,
  native_name  text    NOT NULL,
  direction    text    NOT NULL DEFAULT 'ltr' CHECK (direction IN ('ltr', 'rtl')),
  is_active    boolean NOT NULL DEFAULT true,
  is_default   boolean NOT NULL DEFAULT false,
  sort_order   integer NOT NULL DEFAULT 100,
  created_by uuid, created_at timestamptz NOT NULL DEFAULT now(),
  updated_by uuid, updated_at timestamptz NOT NULL DEFAULT now()
);

-- Exactly one default, and it must stay switched on: it is the fallback every reader lands on.
CREATE UNIQUE INDEX IF NOT EXISTS uq_languages_single_default
  ON qvm_new_apps.languages ((is_default)) WHERE is_default;

INSERT INTO qvm_new_apps.languages (code, english_name, native_name, direction, is_default, sort_order)
VALUES ('en', 'English', 'English',  'ltr', true,  10),
       ('ar', 'Arabic',  'العربية', 'rtl', false, 20)
ON CONFLICT (code) DO NOTHING;

CREATE OR REPLACE FUNCTION qvm_new_apps.default_language_id()
RETURNS integer LANGUAGE sql STABLE SET search_path TO 'qvm_new_apps', 'public' AS $$
  SELECT language_id FROM qvm_new_apps.languages WHERE is_default LIMIT 1;
$$;

-- The reader's language for this request. Set by the API layer the same way the JWT claims are:
--   select set_config('app.lang', 'ar', true);
-- Unset, or set to something unknown, falls back to the default rather than erroring.
CREATE OR REPLACE FUNCTION qvm_new_apps.current_language_id()
RETURNS integer LANGUAGE sql STABLE SET search_path TO 'qvm_new_apps', 'public' AS $$
  SELECT COALESCE(
    (SELECT l.language_id FROM qvm_new_apps.languages l
      WHERE l.is_active AND l.code = NULLIF(current_setting('app.lang', true), '')),
    qvm_new_apps.default_language_id());
$$;

