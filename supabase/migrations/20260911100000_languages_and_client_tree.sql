------------------------------------------------------------------------------ "no empty workshop"
--
-- No foreign key expresses "a workshop must have branches" — the relationship points the other way.
-- A DEFERRED constraint trigger does: the check runs at COMMIT, so a transaction is free to move
-- the last branch from one workshop to another, or to insert a workshop and its branches in either
-- order, and is only refused if it ENDS with a workshop standing empty.

CREATE OR REPLACE FUNCTION qvm_new_apps.assert_workshop_has_branches()
RETURNS trigger LANGUAGE plpgsql SET search_path TO 'qvm_new_apps', 'public' AS $$
DECLARE
  v_ws bigint := COALESCE(NEW.workshop_id, OLD.workshop_id);
  v_n  integer;
BEGIN
  IF v_ws IS NULL THEN RETURN NULL; END IF;
  -- A workshop deleted in the same transaction has nothing left to answer for.
  IF NOT EXISTS (SELECT 1 FROM qvm_new_apps.client_workshops w WHERE w.workshop_id = v_ws) THEN
    RETURN NULL;
  END IF;
  SELECT count(*) INTO v_n FROM qvm_new_apps.client_branches b WHERE b.workshop_id = v_ws;
  IF v_n = 0 THEN
    RAISE EXCEPTION 'Workshop % would be left with no branches. Add a branch, or deactivate the workshop instead.', v_ws
      USING ERRCODE = 'check_violation';
  END IF;
  RETURN NULL;
END $$;

-- Insert on the workshop side needs its own shim: NEW there carries workshop_id under a different
-- meaning than on the branch side.
CREATE OR REPLACE FUNCTION qvm_new_apps.assert_workshop_has_branches_after_insert()
RETURNS trigger LANGUAGE plpgsql SET search_path TO 'qvm_new_apps', 'public' AS $$
DECLARE v_n integer;
BEGIN
  SELECT count(*) INTO v_n FROM qvm_new_apps.client_branches b WHERE b.workshop_id = NEW.workshop_id;
  IF v_n = 0 THEN
    RAISE EXCEPTION 'Workshop % was created with no branches. A workshop must be created together with at least one branch.', NEW.workshop_id
      USING ERRCODE = 'check_violation';
  END IF;
  RETURN NULL;
END $$;

DROP TRIGGER IF EXISTS trg_workshop_needs_branch_ins ON qvm_new_apps.client_workshops;
CREATE CONSTRAINT TRIGGER trg_workshop_needs_branch_ins
  AFTER INSERT ON qvm_new_apps.client_workshops
  DEFERRABLE INITIALLY DEFERRED FOR EACH ROW
  EXECUTE FUNCTION qvm_new_apps.assert_workshop_has_branches_after_insert();

DROP TRIGGER IF EXISTS trg_workshop_needs_branch_del ON qvm_new_apps.client_branches;
CREATE CONSTRAINT TRIGGER trg_workshop_needs_branch_del
  AFTER DELETE OR UPDATE OF workshop_id ON qvm_new_apps.client_branches
  DEFERRABLE INITIALLY DEFERRED FOR EACH ROW
  EXECUTE FUNCTION qvm_new_apps.assert_workshop_has_branches();

------------------------------------------------------------------------------ resolved views
--
-- The fallback chain — the reader's language, then the default, then whatever exists — is written
-- ONCE, here. Every RPC selects a plain `name` from these views and never learns about languages.

CREATE OR REPLACE VIEW qvm_new_apps.v_client_companies AS
SELECT c.company_id, c.cr_number, c.vat_number, c.is_active,
       d.name, d.description, d.language_id AS name_language_id
FROM qvm_new_apps.client_companies c
LEFT JOIN LATERAL (
  SELECT d.* FROM qvm_new_apps.client_companies_descriptions d
   WHERE d.company_id = c.company_id
   ORDER BY (d.language_id = qvm_new_apps.current_language_id()) DESC,
            (d.language_id = qvm_new_apps.default_language_id()) DESC,
            d.language_id
   LIMIT 1
) d ON true;

CREATE OR REPLACE VIEW qvm_new_apps.v_client_workshops AS
SELECT w.workshop_id, w.company_id, w.city, w.region_id, w.location_lat, w.location_lng, w.is_active,
       d.name, d.description, d.language_id AS name_language_id,
       (SELECT count(*) FROM qvm_new_apps.client_branches b WHERE b.workshop_id = w.workshop_id) AS branch_count
FROM qvm_new_apps.client_workshops w
LEFT JOIN LATERAL (
  SELECT d.* FROM qvm_new_apps.client_workshops_descriptions d
   WHERE d.workshop_id = w.workshop_id
   ORDER BY (d.language_id = qvm_new_apps.current_language_id()) DESC,
            (d.language_id = qvm_new_apps.default_language_id()) DESC,
            d.language_id
   LIMIT 1
) d ON true;

CREATE OR REPLACE VIEW qvm_new_apps.v_client_branches AS
SELECT b.customer_id, b.workshop_id, b.list_data_id AS company_id, b.city, b.region_id,
       b.location_lat, b.location_lng, b.is_bulk_client, b.order_category, b.zoho_id,
       -- The untranslated column stays the last resort: a branch created before this migration and
       -- never given a description still has a name to show.
       COALESCE(d.name, b.branch_name) AS name,
       d.description, d.language_id AS name_language_id,
       b.branch_name AS legacy_branch_name
FROM qvm_new_apps.client_branches b
LEFT JOIN LATERAL (
  SELECT d.* FROM qvm_new_apps.client_branches_descriptions d
   WHERE d.customer_id = b.customer_id
   ORDER BY (d.language_id = qvm_new_apps.current_language_id()) DESC,
            (d.language_id = qvm_new_apps.default_language_id()) DESC,
            d.language_id
   LIMIT 1
) d ON true;

