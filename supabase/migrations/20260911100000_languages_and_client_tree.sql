-- Every existing branch becomes a workshop of the same name holding that one branch. On this data
-- the branches ARE the workshops — "PAC", "Body and Paint", "PCVC" are Petromin's workshops, not
-- its addresses — so this backfill states what is already true and leaves the admin to add real
-- branches underneath rather than to untangle a placeholder.
DO $backfill$
DECLARE
  r record;
  v_ws bigint;
  v_lang integer;
BEGIN
  FOR r IN SELECT cb.customer_id, cb.branch_name, cb.list_data_id, cb.city, cb.region_id,
                  cb.location_lat, cb.location_lng
             FROM qvm_new_apps.client_branches cb
            WHERE cb.workshop_id IS NULL
  LOOP
    -- A branch whose company row is missing (deleted list_data) gets one so the tree stays whole.
    INSERT INTO qvm_new_apps.client_companies (company_id) VALUES (r.list_data_id)
    ON CONFLICT (company_id) DO NOTHING;

    INSERT INTO qvm_new_apps.client_workshops (company_id, city, region_id, location_lat, location_lng)
    VALUES (r.list_data_id, r.city, r.region_id, r.location_lat, r.location_lng)
    RETURNING workshop_id INTO v_ws;

    v_lang := (SELECT language_id FROM qvm_new_apps.languages
                WHERE code = CASE WHEN COALESCE(r.branch_name, '') ~ '[؀-ۿ]' THEN 'ar' ELSE 'en' END);

    INSERT INTO qvm_new_apps.client_workshops_descriptions (workshop_id, company_id, language_id, name)
    VALUES (v_ws, r.list_data_id, v_lang, COALESCE(NULLIF(btrim(r.branch_name), ''), 'Workshop ' || v_ws));

    INSERT INTO qvm_new_apps.client_branches_descriptions (customer_id, language_id, name)
    VALUES (r.customer_id, v_lang, COALESCE(NULLIF(btrim(r.branch_name), ''), 'Branch ' || r.customer_id))
    ON CONFLICT (customer_id, language_id) DO NOTHING;

    UPDATE qvm_new_apps.client_branches SET workshop_id = v_ws WHERE customer_id = r.customer_id;
  END LOOP;
END $backfill$;

