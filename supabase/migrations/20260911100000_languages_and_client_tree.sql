-- One place that answers "which branches may this user see". The scoping rule is currently copied
-- through a dozen dashboard RPCs; that duplication is how an empty dashboard shipped once already.
-- NULL means unrestricted — an internal user with no assignment sees everything, and returning an
-- empty array here instead would quietly mean "nothing".
CREATE OR REPLACE FUNCTION qvm_new_apps.effective_branch_ids(p_user_id uuid)
RETURNS integer[] LANGUAGE plpgsql STABLE SECURITY DEFINER
SET search_path TO 'qvm_new_apps', 'public' AS $$
DECLARE
  v_type int;
  v_role int;
  v_branch int;
  v_ids integer[];
BEGIN
  SELECT user_type, user_role, user_branch INTO v_type, v_role, v_branch
  FROM qvm_new_apps.user_data WHERE user_id = p_user_id;
  IF v_type IS NULL THEN RETURN ARRAY[]::integer[]; END IF;

  SELECT array_agg(DISTINCT b) INTO v_ids FROM (
    -- branches assigned outright, on either side of the house
    SELECT ub.client_branch_id AS b FROM qvm_new_apps.user_branches ub WHERE ub.user_id = p_user_id
    UNION
    SELECT iub.branch_id FROM qvm_new_apps.internal_user_branches iub WHERE iub.user_id = p_user_id
    UNION
    -- every branch under a workshop the user belongs to
    SELECT cb.customer_id FROM qvm_new_apps.user_workshops uw
      JOIN qvm_new_apps.client_branches cb ON cb.workshop_id = uw.workshop_id
     WHERE uw.user_id = p_user_id
    UNION
    -- the single branch on user_data, still the only scope some accounts have
    SELECT v_branch WHERE v_branch IS NOT NULL
  ) s WHERE b IS NOT NULL;

  IF v_ids IS NULL AND v_type = 185 THEN
    RETURN NULL;              -- internal, unassigned: no restriction
  END IF;
  RETURN COALESCE(v_ids, ARRAY[]::integer[]);
END $$;

