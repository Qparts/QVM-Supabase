CREATE TABLE IF NOT EXISTS qvm_new_apps.client_branches_descriptions (
  customer_id integer NOT NULL REFERENCES qvm_new_apps.client_branches(customer_id) ON DELETE CASCADE,
  language_id integer NOT NULL REFERENCES qvm_new_apps.languages(language_id),
  name        text    NOT NULL CHECK (btrim(name) <> ''),
  description text,
